def bundle(data: dict[str, Path]) -> str:
    """The code, and [data] (its path in the bundle: the local file)."""
    buf = io.BytesIO()
    with tarfile.open(fileobj=buf, mode="w:gz") as t:
        for pattern in CODE:
            for f in sorted(HERE.glob(pattern)):
                t.add(f, arcname=str(f.relative_to(HERE)))
        for name, f in data.items():
            t.add(f, arcname=name)
    return base64.b64encode(buf.getvalue()).decode()


def user() -> str:
    """The account the kernels belong to. The credentials themselves are the kaggle CLI's: KAGGLE_API_TOKEN (the
    tokens of Settings > API > Generate New Token, CLI 1.8+) or the legacy KAGGLE_KEY."""
    name = os.environ.get("KAGGLE_USERNAME")
    if not name:
        sys.exit("KAGGLE_USERNAME must be set (the Kaggle user name), with KAGGLE_API_TOKEN or KAGGLE_KEY")
    return name


def slug(stage: str) -> str:
    return f"{user()}/pardes-semantic-{stage}"


def kaggle(*args: str, capture: bool = False) -> str:
    r = subprocess.run(["kaggle", *args], check=True, text=True, capture_output=capture)
    return r.stdout if capture else ""


def upload(stage: str, files: dict[str, Path], dry_run: bool) -> str:
    """[files] (their names in it: the local files) as the stage's private dataset, `<user>/pardes-semantic-<stage>-data`,
    created or given a new version, and ready before the kernel that reads it is pushed. Its slug."""
    name = f"pardes-semantic-{stage}-data"
    ds = f"{user()}/{name}"
    d = BUILD / name
    shutil.rmtree(d, ignore_errors=True)
    d.mkdir(parents=True)
    for arcname, f in files.items():
        shutil.copy(f, d / arcname)
    meta = {"title": name, "id": ds, "licenses": [{"name": "other"}]}
    (d / "dataset-metadata.json").write_text(json.dumps(meta, indent=2) + "\n", "utf-8")
    if dry_run:
        return ds
    known = subprocess.run(["kaggle", "datasets", "status", ds], capture_output=True, text=True)
    if known.returncode == 0 and "ready" in known.stdout:
        kaggle("datasets", "version", "-p", str(d), "-m", f"{stage} {time.strftime('%Y-%m-%d %H:%M')}")
    else:
        kaggle("datasets", "create", "-p", str(d))
    for _ in range(180):  # a teacher's embeddings (1.45 GB) take Kaggle longer than the searches
        time.sleep(10)
        if "ready" in kaggle("datasets", "status", ds, capture=True):
            return ds
    sys.exit(f"{ds} is not ready after 30 min")


def quota_left(cap: float) -> tuple[float, float, float, float, str]:
    """The GPU hours left under [cap] of the account's weekly quota, with the hours used, those held by running sessions
    (any of the account's, not only these stages'), the quota and when it renews."""
    from datetime import timedelta

    from kaggle import api

    r = api.quota_view()
    q = r.gpu_quota
    hours = lambda t: (t or timedelta()).total_seconds() / 3600  # noqa: E731
    used, held, total = hours(q.time_used), hours(q.time_reserved), hours(q.total_time_allowed)
    return cap * total - used - held, used, held, total, f"{r.quota_refresh_time} UTC"


def check_quota(stage: str, opts: argparse.Namespace) -> None:
    """Refuses a stage whose --hours would take the week's GPU use past --quota-cap of the quota: the stages that train
    stop by their --hours (and pool ranks no model after them), so a stage that fits is a stage that ends in time."""
    left, used, held, total, renews = quota_left(opts.quota_cap)
    print(f"GPU quota: {used:.1f} h used, {held:.1f} h held by running sessions, of {total:.1f} h; {left:.1f} h left "
          f"under {opts.quota_cap:.0%}")
    if opts.hours > left:
        sys.exit(f"Not pushed: {stage} with --hours {opts.hours:g} would pass {opts.quota_cap:.0%} of the weekly GPU "
                 f"quota ({left:.1f} h left). Give it fewer --hours, or wait for the quota to renew ({renews}).")


def kernels_of(opts: argparse.Namespace) -> dict[str, str]:
    """--from's "tune=tune2,distill=distill2": the kernel each stage named ran under (--as), when not its own."""
    pairs = [p.split("=", 1) for p in (opts.from_ or "").split(",") if p]
    if any(len(p) != 2 or p[0] not in STAGES for p in pairs):
        sys.exit(f"--from takes <stage>=<kernel name>, comma separated, of the stages {', '.join(STAGES)}")
    return dict(pairs)


