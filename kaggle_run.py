os.chdir(SRC)

def sh(cmd):
    print(f"[{(time.time() - START) / 60:.0f} min] $ {cmd}", flush=True)
    subprocess.run(cmd, shell=True, check=True)

sh("nvidia-smi --query-gpu=name,memory.total --format=csv; df -h /kaggle/working /tmp | tail -2")
